"""Generate the 1889 static tables from the 18xx.games engine.

Stage 1: ``dump_1889.rb`` reads the Ruby engine's 1889 game objects and
constants; ``build`` indexes them, derives path masks and the upgrade table,
and ``render`` writes ``tables.json`` one record per line. Stage 2:
``render_cython`` turns ``tables.json`` into ``tables.pxd`` and ``tables.pyx``,
the C arrays the engine cimports. Both stages are byte-identical on re-run.

    .venv/bin/python -m g1889.data.generate                # both stages (needs ruby)
    .venv/bin/python -m g1889.data.generate --cython-only  # stage 2 only
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import textwrap
from math import prod
from pathlib import Path
from typing import Any

from g1889.data import (
    COLORS, LABELS, MARKET_TYPES, NODE, NUM_PAIRS, NUM_SIDES, PAIR_INDEX, PAIRS, RC_TYPES, TABLES_PATH, TERRAINS,
    mask_exits, path_mask, rotate_endpoint,
)

DUMP_SCRIPT = Path(__file__).with_name('dump_1889.rb')
PXD_PATH = Path(__file__).with_name('tables.pxd')
PYX_PATH = Path(__file__).with_name('tables.pyx')
GENERATED = '# Generated by g1889/data/generate.py from tables.json. Do not edit.'
C_RANGES = {'int8_t': (-2**7, 2**7 - 1), 'uint8_t': (0, 2**8 - 1), 'int16_t': (-2**15, 2**15 - 1),
            'uint32_t': (0, 2**32 - 1)}
TRAIN_KEYS = {'name', 'distance', 'price', 'num', 'rusts_on', 'available_on', 'discount', 'events'}
PHASE_KEYS = {'name', 'on', 'train_limit', 'tiles', 'operating_rounds', 'status'}
NO_PATH = 255  # TILE_PATHS padding


def run_dump() -> dict[str, Any]:
    ruby = shutil.which('ruby')
    if ruby is None:
        raise RuntimeError('ruby is required to read the 18xx engine')
    out = subprocess.run([ruby, str(DUMP_SCRIPT)], check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def _tile(t: dict, hex_index: int) -> dict:
    if any(t['unsupported'].values()) or len(t['revenue_centers']) > 1:
        raise ValueError(f"tile {t['name']} has parts the tables do not model: {t}")
    rc = t['revenue_centers'][0] if t['revenue_centers'] else None
    if rc and rc['type'] != 'offboard' and len(set(rc['phase_revenue'] + [rc['d_revenue']])) != 1:
        raise ValueError(f"tile {t['name']} has phase-dependent city/town revenue")
    paths = [sorted(p) for p in t['paths']]  # Ruby's order, which its path walk follows
    masks = [path_mask(paths, r) for r in range(NUM_SIDES)]
    if mask_exits(masks[0]) != sum(1 << e for e in t['exits']):
        raise ValueError(f"tile {t['name']}: paths disagree with Ruby exits")
    terrains = {name for u in t['upgrades'] for name in u['terrains']}
    return {
        'name': t['name'],
        'color': COLORS.index(t['color']),
        'count': t.get('count', 0),
        'hex': hex_index,
        'label': LABELS.index(t['label'] or ''),
        'rc': RC_TYPES.index(rc['type']) if rc else 0,
        'revenue': rc['phase_revenue'][0] if rc and rc['type'] != 'offboard' else 0,
        'slots': rc['slots'] if rc else 0,
        'cost': sum(u['cost'] for u in t['upgrades']),
        'terrain': sum(1 << TERRAINS.index(name) for name in terrains),
        'blocks_lay': t['blocks_lay'],
        'paths': paths,
        'masks': masks,
    }


def upgrades_to(old: dict, rotation: int, new: dict, new_rotation: int) -> bool:
    """1889-rules.md 8.4.1-8.4.3: the next color, the same label and revenue-center
    type, and every old path kept in place. Slots never shrink on a 1889
    upgrade, so tokens always fit (checked in tests)."""
    return (new['color'] == old['color'] + 1
            and new['label'] == old['label']
            and new['rc'] == old['rc']
            and old['masks'][rotation] & ~new['masks'][new_rotation] == 0)


def _upgrade_rows(tiles: list[dict]) -> list[dict]:
    supply = [i for i, t in enumerate(tiles) if t['hex'] < 0]
    rows = []
    for i, old in enumerate(tiles):
        for rotation in range(NUM_SIDES) if old['hex'] < 0 else (0,):
            to = [[j, r] for j in supply for r in range(NUM_SIDES) if upgrades_to(old, rotation, tiles[j], r)]
            if to:
                rows.append({'from': [i, rotation], 'to': to})
    return rows


def build(dump: dict[str, Any]) -> dict[str, Any]:
    if dump['layout'] != 'flat':
        raise ValueError(f"unexpected layout {dump['layout']}")
    ruby_order = {h['id']: i for i, h in enumerate(dump['hexes'])}
    hexes = sorted(dump['hexes'], key=lambda h: (h['x'], h['y']))
    hex_index = {h['id']: i for i, h in enumerate(hexes)}
    corp_index = {c['sym']: i for i, c in enumerate(dump['corporations'])}
    private_index = {c['sym']: i for i, c in enumerate(dump['companies'])}
    train_index = {t['name']: i for i, t in enumerate(dump['trains'])}
    phase_index = {p['name']: i for i, p in enumerate(dump['phases'])}

    supply = sorted(dump['tiles'], key=lambda t: (COLORS.index(t['color']), int(t['name'])))
    tiles = [_tile(t, -1) for t in supply] + [_tile(h['tile'], i) for i, h in enumerate(hexes)]
    tile_index = {t['name']: i for i, t in enumerate(tiles[:len(supply)])}

    hex_rows, rc_rows = [], []
    for i, h in enumerate(hexes):
        rcs = h['tile']['revenue_centers']
        if rcs:
            rc = rcs[0]
            rc_rows.append({
                'hex': i,
                'type': RC_TYPES.index(rc['type']),
                'port': any(icon['image'].endswith('/port.svg') for icon in h['tile']['icons']),
                'slots': rc['slots'],
                'revenue': rc['phase_revenue'],
                'd_revenue': rc['d_revenue'],
            })
        hex_rows.append({
            'id': h['id'],
            'name': h['location_name'] or '',
            'x': h['x'],
            'y': h['y'],
            'tile': len(supply) + i,
            'neighbors': [hex_index[h['neighbors'][str(s)]] if str(s) in h['neighbors'] else -1
                          for s in range(NUM_SIDES)],
            'exit_mask': sum(1 << s for s in h['open_sides']),
            'rc': len(rc_rows) - 1 if rcs else -1,
            'reserved': [corp_index[sym] for sym in h['reservations']],
            'blockers': [private_index[sym] for sym in h['blockers']],
            'ruby_order': ruby_order[h['id']],
        })

    corporations = []
    for c in dump['corporations']:
        if c['city'] is not None or c['capitalization'] != 'full':
            raise ValueError(f"unexpected corporation setup: {c}")
        corporations.append({
            'sym': c['sym'],
            'name': c['name'],
            'home': hex_index[c['home']],
            'tokens': len(c['token_prices']),
            'token_prices': c['token_prices'],
            'float_percent': c['float_percent'],
            'max_ownership_percent': c['max_ownership_percent'],
        })

    # Ability parameters as Ruby gives them, with hex, tile, and corporation ids indexed.
    ability_index = {'hexes': hex_index, 'tiles': tile_index, 'corporations': corp_index}
    privates = [{
        'sym': c['sym'],
        'name': c['name'],
        'value': c['value'],
        'revenue': c['revenue'],
        'abilities': [{k: [ability_index[k][x] for x in v] if k in ability_index else v for k, v in a.items()}
                      for a in c.get('abilities', [])],
    } for c in dump['companies']]

    trains = []
    for t in dump['trains']:
        if set(t) - TRAIN_KEYS:
            raise ValueError(f"unmodeled train keys: {set(t) - TRAIN_KEYS}")
        trains.append({
            'name': t['name'],
            'distance': t['distance'],
            'price': t['price'],
            'count': -1 if t['num'] == 'unlimited' else t['num'],
            'rusts_on': train_index.get(t.get('rusts_on'), -1),
            'available_on': phase_index.get(t.get('available_on'), -1),
            'trade_in': [t.get('discount', {}).get(name, 0) for name in train_index],
            'events': [e['type'] for e in t.get('events', [])],
        })

    phases = []
    for p in dump['phases']:
        if set(p) - PHASE_KEYS:
            raise ValueError(f"unmodeled phase keys: {set(p) - PHASE_KEYS}")
        phases.append({
            'name': p['name'],
            'on': train_index.get(p.get('on'), -1),
            'train_limit': p['train_limit'],
            'tiles': [COLORS.index(c) for c in p['tiles']],
            'operating_rounds': p['operating_rounds'],
            'status': p.get('status', []),
        })

    market = dump['market']
    if any(cell is None or len(cell['types']) > 1 for row in market for cell in row):
        raise ValueError('market has gaps or multi-type cells')

    return {
        'source': 'Generated by g1889/data/generate.py from submodules/18xx '
                  '(lib/engine/game/g_1889). Do not edit; see g1889/data/__init__.py.',
        'enums': {'colors': COLORS, 'rc_types': RC_TYPES, 'labels': LABELS, 'terrains': TERRAINS,
                  'market_types': MARKET_TYPES},
        'rules': dump['rules'],
        'players': [{
            'players': int(n),
            'starting_cash': p['starting_cash'],
            'cert_limit': p['cert_limit'],
            'privates': [private_index[sym] for sym in p['privates']],
        } for n, p in dump['players'].items()],
        'hexes': hex_rows,
        'revenue_centers': rc_rows,
        'tiles': tiles,
        'upgrades': _upgrade_rows(tiles),
        'corporations': corporations,
        'privates': privates,
        'trains': trains,
        'phases': phases,
        'market_prices': [[cell['price'] for cell in row] for row in market],
        'market_types': [[MARKET_TYPES.index(cell['types'][0] if cell['types'] else '') for cell in row]
                         for row in market],
    }


def render(tables: dict[str, Any]) -> str:
    """JSON with one top-level key per line and one row per line beneath it."""
    def compact(value: Any) -> str:
        return json.dumps(value, separators=(', ', ': '))

    lines = ['{']
    for i, (key, value) in enumerate(tables.items()):
        end = ',' if i < len(tables) - 1 else ''
        if isinstance(value, (list, dict)) and value:
            items = value.items() if isinstance(value, dict) else enumerate(value)
            open_, close = ('{', '}') if isinstance(value, dict) else ('[', ']')
            lines.append(f'  {json.dumps(key)}: {open_}')
            rows = [compact(v) if isinstance(value, list) else f'{json.dumps(k)}: {compact(v)}' for k, v in items]
            lines += [f'    {row},' for row in rows[:-1]] + [f'    {rows[-1]}', f'  {close}{end}']
        else:
            lines.append(f'  {json.dumps(key)}: {compact(value)}{end}')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def _wrapped(items: Any) -> list[str]:
    """Comma-separated items wrapped at 100 columns, indented one level."""
    return textwrap.wrap(', '.join(items) + ',', width=100, initial_indent='    ', subsequent_indent='    ')


def _shape(values: Any) -> tuple[int, ...]:
    return (len(values), *_shape(values[0])) if isinstance(values, list) else ()


def _flat(values: Any) -> list:
    return [v for row in values for v in _flat(row)] if isinstance(values, list) else [values]


def _literal(values: Any) -> str:
    return f'[{", ".join(map(_literal, values))}]' if isinstance(values, list) else str(values)


def _one(values: Any) -> Any:
    """The single value shared by every item of values."""
    distinct = set(values)
    if len(distinct) != 1:
        raise ValueError(f'expected one shared value, got {sorted(distinct)}')
    return distinct.pop()


def render_cython(tables: dict[str, Any]) -> tuple[str, str]:
    """Stage 2: tables.json as the enums and C arrays of tables.pxd and tables.pyx.

    Derives TILE_EXITS, TILE_CANON_ROT, the upgrade CSR (canonical targets
    only), MAX_LAY_CANDIDATES, and the path walk's tables: TILE_PATHS (each
    tile's paths in Ruby's order, by rotation), HEX_WALK_ORDER, and
    ENDPOINT_PAIRS. Every array gets a Python list mirror and every enum
    member an int mirror, set through globals() as in core/data.pyx.
    """
    hexes, rcs, tiles = tables['hexes'], tables['revenue_centers'], tables['tiles']
    corps, privates, trains, phases = (tables[k] for k in ('corporations', 'privates', 'trains', 'phases'))
    prices, types, enums = tables['market_prices'], tables['market_types'], tables['enums']
    hex_ids, tile_names = [h['id'] for h in hexes], [t['name'] for t in tiles]
    num_supply = sum(t['hex'] < 0 for t in tiles)
    phase_index = {p['name']: i for i, p in enumerate(phases)}
    ability = {(p['sym'], a['type']): a for p in privates for a in p['abilities']}
    mf, er = ability['MF', 'tile_lay'], ability['ER', 'tile_lay']
    smr, dr, utf = ability['SMR', 'tile_discount'], ability['DR', 'exchange'], ability['UTF', 'revenue_change']
    if smr['terrain'] != 'mountain' or sorted(mf['hexes']) != sorted(rc['hex'] for rc in rcs if rc['port']):
        raise ValueError('unexpected SMR or MF ability parameters')
    if any(len(h['reserved']) > 1 or len(h['blockers']) > 1 for h in hexes):
        raise ValueError('a hex has several reservations or blockers')
    (d_train,) = [i for i, t in enumerate(trains) if any(t['trade_in'])]
    trade_in_types = [t for t, discount in enumerate(trains[d_train]['trade_in']) if discount]
    par = sorted((prices[r][c], r, c) for r, row in enumerate(types) for c, t in enumerate(row)
                 if enums['market_types'][t] == 'par')
    counts = {p['players']: p for p in tables['players']}
    market_cols = max(map(len, prices))

    canon = [[t['masks'].index(m) for m in t['masks']] for t in tiles]
    max_paths = max(len(t['paths']) for t in tiles)
    tile_paths = [[[PAIR_INDEX[rotate_endpoint(a, r)][rotate_endpoint(b, r)] for a, b in t['paths']]
                   + [NO_PATH] * (max_paths - len(t['paths'])) for r in range(NUM_SIDES)] for t in tiles]
    exits = [[mask_exits(m) for m in t['masks']] for t in tiles]
    rows = {tuple(row['from']): row['to'] for row in tables['upgrades']}
    csr = [sorted({(new, canon[new][r]) for new, r in rows.get((t, rot), [])})
           for t in range(len(tiles)) for rot in range(NUM_SIDES)]
    # Candidates a corp may lay over any tile state on any hex, once the
    # hex's open sides apply (blocks_lay tiles are ability-only).
    max_lay = max(
        sum(not tiles[new]['blocks_lay'] and exits[new][r] & ~h['exit_mask'] == 0
            for new, r in csr[old * NUM_SIDES + rot])
        for h in hexes
        for old, rot in [(h['tile'], 0)] + [(t, r) for t in range(num_supply) for r in range(NUM_SIDES)])

    def members(prefix: str, names: list[str], bits: bool = False) -> list[tuple[str, int]]:
        return [(f'{prefix}_{name.upper()}', 1 << i if bits else i) for i, name in enumerate(names)]

    enum_defs = [
        ('TableDims', [
            ('NUM_HEXES', len(hexes)), ('NUM_RCS', len(rcs)), ('NUM_SUPPLY_TILES', num_supply),
            ('NUM_TILES', len(tiles)), ('NUM_CORPS', len(corps)), ('NUM_PRIVATES', len(privates)),
            ('NUM_TRAIN_TYPES', len(trains)), ('NUM_GAME_PHASES', len(phases)), ('MARKET_ROWS', len(prices)),
            ('MARKET_COLS', market_cols), ('NUM_PAR_PRICES', len(par)), ('NUM_SIDES', NUM_SIDES),
            ('NODE', NODE), ('NUM_PAIRS', NUM_PAIRS), ('NUM_PORTS', len(mf['hexes'])),
            ('MAX_CITY_SLOTS', max(t['slots'] for t in tiles)), ('MAX_CORP_TOKENS', max(c['tokens'] for c in corps)),
            ('NUM_ER_TILES', len(er['tiles'])), ('NUM_TRADE_IN_TYPES', len(trade_in_types)),
            ('MIN_PLAYERS', min(counts)), ('MAX_PLAYERS', max(counts)),
            ('NUM_UPGRADE_TARGETS', sum(map(len, csr))), ('MAX_LAY_CANDIDATES', max_lay),
            ('MAX_ROUTE_HEXES', 2 * len(hexes)),  # a route can cross a hex twice on a crossing tile
            ('MAX_TILE_PATHS', max_paths),
        ]),
        ('TableRules', [
            ('BANK_CASH', tables['rules']['BANK_CASH']), ('MIN_BID_INCREMENT', tables['rules']['MIN_BID_INCREMENT']),
            ('MARKET_SHARE_LIMIT', tables['rules']['MARKET_SHARE_LIMIT']),
            ('MAX_OWNERSHIP_PERCENT', _one(c['max_ownership_percent'] for c in corps)),
            ('FLOAT_PERCENT', _one(c['float_percent'] for c in corps)),
            ('SMR_DISCOUNT', smr['discount']), ('UTF_LATE_REVENUE', utf['revenue']),
            ('UTF_LATE_PHASE', phase_index[utf['on_phase']]),
            ('CLOSE_PRIVATES_PHASE', _one(i for i, p in enumerate(phases)
                                          if p['on'] >= 0 and 'close_companies' in trains[p['on']]['events'])),
            ('ER_HEX', _one(er['hexes'])), ('PORT_TILE', _one(mf['tiles'])),
            ('DR_EXCHANGE_CORP', _one(dr['corporations'])), ('D_TRAIN', d_train),
        ]),
        ('TileColor', members('COLOR', enums['colors'])),
        ('RcType', members('RC', enums['rc_types'])),
        ('TileLabel', members('LABEL', [label or 'none' for label in enums['labels']])),
        ('TerrainBit', members('TERRAIN', enums['terrains'], bits=True)),
        ('MarketType', members('MARKET', [t or 'normal' for t in enums['market_types']])),
        ('CorpId', members('CORP', [c['sym'] for c in corps])),
        ('PrivateId', members('PRIVATE', [p['sym'] for p in privates])),
        ('TrainType', members('TRAIN', [t['name'] for t in trains])),
        ('GamePhase', members('GAME_PHASE', [p['name'] for p in phases])),
    ]

    pxd_arrays: list[str] = []
    pyx_arrays: list[str] = []
    mirrors: list[str] = []

    def section(title: str) -> None:
        pxd_arrays.extend(['', f'# {title}'])
        pyx_arrays.extend(['', f'# {title}'])

    def array(ctype: str, name: str, values: list, labels: list | None = None,
              groups: list[tuple[str, list]] | None = None) -> None:
        """One C array: a row per line for 2D and 3D (labelled), a group per line or wrapped for 1D."""
        if isinstance(values[0], list):
            shape = _shape(values)
            flat = _flat(values)
            if len(flat) != prod(shape):
                raise ValueError(f'{name} is ragged')
            body = [f'    {_literal(row)},' + (f'  # {labels[i]}' if labels else '') for i, row in enumerate(values)]
            index = ''.join(f'[{"ijk"[d]}]' for d in range(len(shape)))
            mirror = f'<int>{name}{index}'
            for d in reversed(range(len(shape))):
                mirror = f'[{mirror} for {"ijk"[d]} in range({shape[d]})]'
        else:
            shape = (len(values),)
            flat = values
            if groups is not None:
                if [v for _, vals in groups for v in vals] != values:
                    raise ValueError(f'{name} groups do not cover its values')
                body = [f'    {", ".join(map(str, vals))},  # {label}' for label, vals in groups if vals]
            else:
                body = _wrapped(map(str, values))
            mirror = f'[<int>{name}[i] for i in range({shape[0]})]'
        low, high = C_RANGES[ctype]
        if not all(low <= v <= high for v in flat):
            raise ValueError(f'{name} has values outside {ctype}')
        decl = f'cdef {ctype}{"".join(f"[{d}]" for d in shape)} {name}'
        pxd_arrays.append(decl)
        inline = f'{decl} = [{", ".join(map(str, values))}]'
        pyx_arrays.extend([inline] if len(shape) == 1 and groups is None and len(inline) <= 100
                          else [f'{decl} = [', *body, ']'])
        mirrors.append(f"globals()['{name}'] = {mirror}")

    rc_ids = [hex_ids[rc['hex']] for rc in rcs]
    section('Hexes: neighbors[s] is the hex across side s or -1; exit bit s set when track may leave through s')
    array('int8_t', 'HEX_NEIGHBOR', [h['neighbors'] for h in hexes], hex_ids)
    array('uint8_t', 'HEX_EXIT_MASK', [h['exit_mask'] for h in hexes])
    array('int8_t', 'HEX_RC', [h['rc'] for h in hexes])
    array('int8_t', 'HEX_HOME_CORP', [h['reserved'][0] if h['reserved'] else -1 for h in hexes])
    array('int8_t', 'HEX_BLOCKER', [h['blockers'][0] if h['blockers'] else -1 for h in hexes])
    array('int8_t', 'HEX_WALK_ORDER', sorted(range(len(hexes)), key=lambda i: hexes[i]['ruby_order']))
    section('Revenue centers: printed values; revenue by game phase for non-D trains')
    array('int8_t', 'RC_HEX', [rc['hex'] for rc in rcs])
    array('int8_t', 'RC_TYPE', [rc['type'] for rc in rcs])
    array('int8_t', 'RC_PORT', [int(rc['port']) for rc in rcs])
    array('int16_t', 'RC_REVENUE', [rc['revenue'] for rc in rcs], rc_ids)
    array('int16_t', 'RC_D_REVENUE', [rc['d_revenue'] for rc in rcs])
    section('Tiles: 0-39 supply, 40 + h printed on hex h; masks, exits, canonical rotations, and paths by rotation')
    for ctype, name, key in (('uint8_t', 'TILE_COLOR', 'color'), ('uint8_t', 'TILE_LABEL', 'label'),
                             ('uint8_t', 'TILE_RC', 'rc'), ('uint8_t', 'TILE_SLOTS', 'slots'),
                             ('uint8_t', 'TILE_TERRAIN', 'terrain'), ('uint8_t', 'TILE_BLOCKS_LAY', 'blocks_lay'),
                             ('int16_t', 'TILE_COUNT', 'count'), ('int16_t', 'TILE_REVENUE', 'revenue'),
                             ('int16_t', 'TILE_COST', 'cost')):
        array(ctype, name, [int(t[key]) for t in tiles])
    array('uint32_t', 'TILE_MASK', [t['masks'] for t in tiles], tile_names)
    array('uint8_t', 'TILE_EXITS', exits, tile_names)
    array('uint8_t', 'TILE_CANON_ROT', canon, tile_names)
    array('uint8_t', 'TILE_PATH_COUNT', [len(t['paths']) for t in tiles])
    array('uint8_t', 'TILE_PATHS', tile_paths, tile_names)
    section('Upgrades: CSR over k = 6 * tile + rotation; k has targets UPG_START[k] to UPG_START[k + 1] - 1')
    starts = [0]
    for targets in csr:
        starts.append(starts[-1] + len(targets))
    array('int16_t', 'UPG_START', starts,
          groups=[(tile_names[t], starts[t * NUM_SIDES:(t + 1) * NUM_SIDES]) for t in range(len(tiles))]
          + [('end', starts[-1:])])
    key_labels = [f'{tile_names[k // NUM_SIDES]} r{k % NUM_SIDES}' for k in range(len(csr))]
    array('uint8_t', 'UPG_TILE', [new for targets in csr for new, _ in targets],
          groups=[(key_labels[k], [new for new, _ in targets]) for k, targets in enumerate(csr)])
    array('uint8_t', 'UPG_ROT', [r for targets in csr for _, r in targets],
          groups=[(key_labels[k], [r for _, r in targets]) for k, targets in enumerate(csr)])
    section('Corporations and privates')
    array('int8_t', 'CORP_HOME', [c['home'] for c in corps])
    array('int8_t', 'CORP_TOKENS', [c['tokens'] for c in corps])
    max_tokens = max(c['tokens'] for c in corps)
    array('int16_t', 'CORP_TOKEN_PRICE', [c['token_prices'] + [0] * (max_tokens - c['tokens']) for c in corps],
          [c['sym'] for c in corps])
    array('int16_t', 'PRIVATE_VALUE', [p['value'] for p in privates])
    array('int16_t', 'PRIVATE_REVENUE', [p['revenue'] for p in privates])
    array('int8_t', 'MF_PORT_HEX', mf['hexes'])
    array('int8_t', 'ER_TILE', er['tiles'])
    section('Players, indexed by player count; PRIVATES_IN_PLAY is a private bitmask')
    by_count = [counts.get(n) for n in range(max(counts) + 1)]
    array('int16_t', 'START_CASH', [p['starting_cash'] if p else 0 for p in by_count])
    array('int16_t', 'CERT_LIMIT', [p['cert_limit'] if p else 0 for p in by_count])
    array('uint8_t', 'PRIVATES_IN_PLAY', [sum(1 << i for i in p['privates']) if p else 0 for p in by_count])
    section('Trains: count -1 is unlimited; rusts_on is a train type, available_on a game phase, or -1')
    for name, key in (('TRAIN_DISTANCE', 'distance'), ('TRAIN_PRICE', 'price'), ('TRAIN_COUNT', 'count'),
                      ('TRAIN_RUSTS_ON', 'rusts_on'), ('TRAIN_AVAILABLE_ON', 'available_on')):
        array('int16_t', name, [t[key] for t in trains])
    array('int16_t', 'TRAIN_TRADE_IN', [t['trade_in'] for t in trains], [t['name'] for t in trains])
    array('int8_t', 'TRADE_IN_TYPE', trade_in_types)
    section('Game phases (PHASE_TILE_COLORS is a TileColor bitmask) and the market (price 0 = no cell)')
    array('int8_t', 'PHASE_ON_TRAIN', [p['on'] for p in phases])
    array('int8_t', 'PHASE_TRAIN_LIMIT', [p['train_limit'] for p in phases])
    array('int8_t', 'PHASE_TILE_COLORS', [sum(1 << c for c in p['tiles']) for p in phases])
    array('int8_t', 'PHASE_ORS', [p['operating_rounds'] for p in phases])
    array('int8_t', 'PHASE_CAN_BUY_PRIVATES', [int('can_buy_companies' in p['status']) for p in phases])
    array('int16_t', 'MARKET_PRICE', [row + [0] * (market_cols - len(row)) for row in prices])
    array('uint8_t', 'MARKET_TYPE', [row + [0] * (market_cols - len(row)) for row in types])
    array('int8_t', 'MARKET_ROW_LEN', [len(row) for row in prices])
    section('Par prices, ascending')
    array('int8_t', 'PAR_ROW', [r for _, r, _ in par])
    array('int8_t', 'PAR_COL', [c for _, _, c in par])
    array('int16_t', 'PAR_PRICE', [p for p, _, _ in par])
    section('Endpoint pairs: bit i of a path mask joins PAIR_A[i] and PAIR_B[i]; ENDPOINT_PAIRS[e] has the pairs at e')
    array('uint8_t', 'PAIR_A', [a for a, _ in PAIRS])
    array('uint8_t', 'PAIR_B', [b for _, b in PAIRS])
    array('uint32_t', 'ENDPOINT_PAIRS', [sum(1 << i for i, pair in enumerate(PAIRS) if e in pair)
                                         for e in range(NODE + 1)])

    enum_lines = []
    for name, values in enum_defs:
        enum_lines += ['', f'cpdef enum {name}:'] + [f'    {k} = {v}' for k, v in values]
    pxd = '\n'.join([
        GENERATED,
        '# Static 1889 tables; conventions are in g1889/data/__init__.py.',
        '',
        'from libc.stdint cimport int8_t, int16_t, uint8_t, uint32_t',
        *enum_lines,
        *pxd_arrays,
    ]) + '\n'
    names = [('HEX_IDS', hex_ids), ('TILE_NAMES', tile_names), ('CORP_SYMS', [c['sym'] for c in corps]),
             ('PRIVATE_SYMS', [p['sym'] for p in privates]), ('TRAIN_NAMES', [t['name'] for t in trains]),
             ('PHASE_NAMES', [p['name'] for p in phases])]
    pyx = '\n'.join([
        GENERATED,
        '"""Static 1889 tables as C arrays; tables.pxd declares them for cimport.',
        '',
        'Python callers get a list mirror of each array under its name, every enum',
        'member as an int, and the 18xx string ids below. The engine never reads',
        'tables.json; conventions are in g1889/data/__init__.py.',
        '"""',
        *pyx_arrays,
        '',
        '# Python mirrors: a bare assignment would be shadowed by the cdef names.',
        *mirrors,
        'for _enum in (', *_wrapped([name for name, _ in enum_defs]), '):',
        '    for _name, _member in _enum.__members__.items():',
        '        globals()[_name] = int(_member)',
        'del _enum, _name, _member',
        *(line for name, values in names for line in ['', f'{name} = (', *_wrapped(map(repr, values)), ')']),
    ]) + '\n'
    return pxd, pyx


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--cython-only', action='store_true',
                        help='regenerate tables.pxd/.pyx from the checked-in tables.json, without Ruby')
    args = parser.parse_args(argv)
    if not args.cython_only:
        TABLES_PATH.write_text(render(build(run_dump())))
        print(f'wrote {TABLES_PATH}')
    pxd, pyx = render_cython(json.loads(TABLES_PATH.read_text()))
    for path, text in ((PXD_PATH, pxd), (PYX_PATH, pyx)):
        path.write_text(text)
        print(f'wrote {path}')


if __name__ == '__main__':
    main()
